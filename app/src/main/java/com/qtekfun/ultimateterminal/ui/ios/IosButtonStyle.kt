package com.qtekfun.ultimateterminal.ui.ios

/** How a button is filled. */
enum class IosButtonStyle {
    /** A solid tint with light text: the main action. */
    FILLED,

    /** A pale tint behind tinted text: a secondary action. */
    TINTED,

    /** Only tinted text. */
    PLAIN
}
